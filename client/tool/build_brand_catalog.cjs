// Rebuild from the pinned Simple Icons npm package and downloaded Dashboard Icons.
// node tool/build_brand_catalog.cjs <simple-icons-package> <dashboard-assets> <dashboard-revision>
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const simple = path.resolve(process.argv[2]), dashboard = path.resolve(process.argv[3]), revision = process.argv[4];
const data = JSON.parse(fs.readFileSync(path.join(simple, 'data/simple-icons.json')));
const custom = JSON.parse(fs.readFileSync(path.join(__dirname, 'brand-overrides.json')));
const normalize = value => value.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const excluded = /(^|\.)(github\.com|githubusercontent\.com|wikimedia\.org|wikipedia\.org|figma\.com|google\.com|gstatic\.com|simpleicons\.org|simple-icons\.org|behance\.net|dribbble\.com|wixstatic\.com|wordpress\.com|medium\.com|notion\.site|gitlab\.com|archive\.org|youtube\.com|amazonaws\.com|cloudfront\.net)$/;
const claims = new Map();
for (const icon of data) {
  let host; try { host = new URL(icon.source).hostname.toLowerCase().replace(/^www\./,''); } catch { continue; }
  if (!excluded.test(host)) { if (!claims.has(host)) claims.set(host, []); claims.get(host).push(icon.slug); }
}
const catalog = new Map();
for (const icon of data) {
  const domains = [...claims].filter(([, slugs]) => slugs.length === 1 && slugs[0] === icon.slug).map(([host]) => host);
  catalog.set(icon.slug, { ...icon, domains, names: [...new Set([normalize(icon.title),normalize(icon.slug),...(icon.aliases?.aka || []).map(normalize)])] });
  const svg = fs.readFileSync(path.join(simple, 'icons', icon.slug + '.svg'));
  if (/<script|<image|<use\b|href=/i.test(svg.toString())) throw Error('Unsafe artwork: ' + icon.slug);
  fs.writeFileSync(path.join(root, 'assets/brands', icon.slug + '.svg'), svg);
}
for (const [slug, override] of Object.entries(custom)) {
  const old = catalog.get(slug) || { slug, title: override.title, hex:'2563EB', names:[] };
  catalog.set(slug, {...old,...override,names:[...new Set([...old.names,normalize(override.title || old.title),...(override.names || [])].map(normalize))]});
}
const provenance = [];
for (const icon of catalog.values()) {
  const png = path.join(dashboard, icon.slug + '.png');
  if (fs.existsSync(png)) {
    fs.copyFileSync(png, path.join(root, 'assets/brands', icon.slug + '.png'));
    icon.fullColor = true;
    provenance.push({slug:icon.slug,revision,url:`https://raw.githubusercontent.com/homarr-labs/dashboard-icons/${revision}/png/${icon.slug}.png`,sha256:crypto.createHash('sha256').update(fs.readFileSync(png)).digest('hex')});
  } else if (!fs.existsSync(path.join(root,'assets/brands',icon.slug+'.svg'))) throw Error('Missing asset '+icon.slug);
}
const quote = value => JSON.stringify(value).replace(/\$/g,'\\$');
const list = items => '['+items.map(quote).join(',')+']';
const rows = [...catalog.values()].sort((a,b)=>a.title.localeCompare(b.title,'en')).map(icon => `  BrandLogo(${quote(icon.slug)}, ${quote(icon.title)}, Color(0xff${icon.hex}), ${list(icon.domains || [])}, ${list(icon.names)}, fullColor: ${!!icon.fullColor}),`);
fs.writeFileSync(path.join(root,'lib/vault/brand_catalog.g.dart'),"// Generated by tool/build_brand_catalog.cjs. Do not edit by hand.\npart of 'credential_logo.dart';\nconst brandLogos = <BrandLogo>[\n"+rows.join('\n')+'\n];\n');
fs.writeFileSync(path.join(root,'third_party/simple-icons/sources.json'),JSON.stringify({project:'Simple Icons',version:'16.0.0',revision:'28241d80f8422eaed317ef968ad1e40b6d0d9163',icons:data.map(icon=>({...icon,asset_sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(simple,'icons',icon.slug+'.svg'))).digest('hex')}))},null,2));
fs.mkdirSync(path.join(root,'third_party/dashboard-icons'),{recursive:true});
fs.writeFileSync(path.join(root,'third_party/dashboard-icons/sources.json'),JSON.stringify({project:'Dashboard Icons',revision,icons:provenance},null,2));
fs.copyFileSync(path.join(dashboard,'LICENSE'),path.join(root,'third_party/dashboard-icons/LICENSE'));
console.log(`Generated ${catalog.size} brands, including ${provenance.length} full-color images.`);
